/** Ordered list of platforms to show — the footer iterates and renders
    any whose href is non-empty in the CMS-managed social map. */
export const SOCIAL_PLATFORMS = ["facebook", "x", "linkedin", "youtube", "tiktok", "instagram"];

export function SocialIcons({
  social,
  className = "",
}: {
  social: Record<string, string>;
  className?: string;
}) {
  const links = SOCIAL_PLATFORMS.map((platform) => ({
    platform,
    href: social[platform] ?? "",
  })).filter((l) => Boolean(l.href));

  if (links.length === 0) return null;

  return (
    <div
      className={`flex items-center gap-3 ${className}`}
      aria-label="Follow FOSCOD on social media"
    >
      {links.map(({ platform, href }) => {
        const Icon = ICON_COMPONENTS[platform];
        if (!Icon) return null;
        return (
          <a
            key={platform}
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex h-9 w-9 items-center justify-center rounded-full bg-white/10 text-white transition-colors hover:bg-white/20"
            aria-label={`Follow us on ${platform}`}
          >
            <Icon />
          </a>
        );
      })}
    </div>
  );
}
